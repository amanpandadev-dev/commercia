export function translate(lang: Lang, en: string): string {
  return lang === 'hi' ? (HI[en] ?? en) : en;
}

/** The other language's label, for the small subtitle under headings (like the demo). */
export function other(lang: Lang, en: string): string {
  return lang === 'hi' ? en : (HI[en] ?? '');
}
